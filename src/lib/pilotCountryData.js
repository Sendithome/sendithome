// ─── HELPER FUNCTIONS ─────────────────────────────────────────────────────────

export function getCountryById(id) {
  return PILOT_COUNTRIES.find(c => c.id === id) || PILOT_COUNTRIES[0];
}

export function getPrimaryCountry() {
  return PILOT_COUNTRIES.find(c => c.isPrimary) || PILOT_COUNTRIES[0];
}

export function getMonthlyChartData(country) {
  return MONTHS_SHORT.map((month, i) => ({
    month,
    shipments: country.monthlyShipments[i],
    revenue: country.monthlyRevenue[i],
  }));
}

export function getPilotCountriesComparison() {
  return [...PILOT_COUNTRIES]
    .sort((a, b) => b.totalShipments - a.totalShipments)
    .map(c => ({
      id: c.id,
      name: `${c.flag} ${c.shortName}`,
      fullName: c.name,
      shipments: c.totalShipments,
      addressableMarket: Math.round(c.sihAddressableMarket / 1_000_000),  // $M
      avgSpend: c.avgSpendPerTourist,
      tourists: c.annualTourists,
      hotels: c.activeHotels,
      retailers: c.activeRetailers,
    }));
}

export function getPlatformTotals() {
  return {
    totalShipments: PILOT_COUNTRIES.reduce((s, c) => s + c.totalShipments, 0),
    totalAddressableMarket: PILOT_COUNTRIES.reduce((s, c) => s + c.sihAddressableMarket, 0),
    totalTourists: PILOT_COUNTRIES.reduce((s, c) => s + c.annualTourists, 0),
    totalHotels: PILOT_COUNTRIES.reduce((s, c) => s + c.activeHotels, 0),
    totalRetailers: PILOT_COUNTRIES.reduce((s, c) => s + c.activeRetailers, 0),
    totalProjectedRevenue: PILOT_COUNTRIES.reduce((s, c) => s + c.economicImpact.sihProjectedAnnualRevenue, 0),
    totalGovtCommission: PILOT_COUNTRIES.reduce((s, c) => s + c.economicImpact.govtCommissionEstimate, 0),
  };
}